import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { addJsonToStats, inspectFit, newFieldStats, type FieldStats, type FitInspection } from './inspect';
import type { Manifest } from './types';

/** Evidence searches for the M0 exit questions (regex over JSON field paths). */
const QUESTIONS: Array<{ q: string; endpoints: string[]; pattern: RegExp }> = [
  { q: 'HRV: nightly value + baseline range?', endpoints: ['hrv-daily', 'hrv-day'], pattern: /hrv|baseline|lastNight|weeklyAvg|status/i },
  { q: 'Sleep duration + sleep score?', endpoints: ['sleep-summaries', 'sleep-day'], pattern: /sleepTimeSeconds|score|overall|deep|rem|light/i },
  { q: 'Body Battery at wake / min / max?', endpoints: ['body-battery', 'daily-summaries', 'user-summary-day'], pattern: /bodyBattery|charged|drained|highest|lowest|wake/i },
  { q: 'Resting HR per day?', endpoints: ['daily-summaries', 'user-summary-day', 'heart-rate-day'], pattern: /restingHeartRate|restingHr|minHeartRate/i },
  { q: 'HR zones + max HR in profile?', endpoints: ['hr-zones', 'user-settings'], pattern: /zone|maxHeart|lactate|restingHeart|hrZone/i },
  { q: 'VO2 max in activity summaries?', endpoints: ['activities-search', 'activity-detail'], pattern: /vO2|vo2/i },
  { q: "Garmin's own load / training effect?", endpoints: ['activities-search', 'activity-detail'], pattern: /trainingLoad|TrainingEffect|trainingStress/i },
  { q: 'HR time-in-zone per activity?', endpoints: ['activities-search', 'activity-detail'], pattern: /hrTimeInZone/i },
  { q: 'Swim metrics (pool length, SWOLF, strokes)?', endpoints: ['activities-search', 'activity-detail'], pattern: /pool|swolf|stroke|activeLengths/i },
  { q: 'Fitness Age?', endpoints: ['fitness-age'], pattern: /fitnessAge|chronologicalAge|achievable/i },
];

export function writeCoverage(out: string, manifest: Manifest): void {
  const byEndpoint = new Map<string, { entries: Manifest['entries']; stats: FieldStats }>();
  for (const e of manifest.entries) {
    if (e.endpoint === 'activity-file') continue;
    const slot = byEndpoint.get(e.endpoint) ?? { entries: [], stats: newFieldStats() };
    slot.entries.push(e);
    if (e.file && e.status >= 200 && e.status < 300) {
      try {
        addJsonToStats(slot.stats, JSON.parse(readFileSync(join(out, e.file), 'utf8')));
      } catch {
        /* unreadable fixture: counted as request only */
      }
    }
    byEndpoint.set(e.endpoint, slot);
  }

  const fitDir = join(out, 'fit');
  const fits: FitInspection[] = existsSync(fitDir)
    ? readdirSync(fitDir)
        .filter((f) => f.toLowerCase().endsWith('.fit'))
        .sort()
        .map((f) => inspectFit(f, new Uint8Array(readFileSync(join(fitDir, f)))))
    : [];
  const otherFiles = existsSync(fitDir) ? readdirSync(fitDir).filter((f) => !f.toLowerCase().endsWith('.fit')) : [];
  const fileEntries = manifest.entries.filter((e) => e.endpoint === 'activity-file');

  const L: string[] = [];
  L.push('# Garmin data coverage', '');
  L.push(`Generated by \`scripts/probe.ts\`. Window **${manifest.from} → ${manifest.to}**, run at ${manifest.ranAt}.`, '');
  L.push('> Personal health data. This folder is gitignored — never commit it.', '');
  L.push(`Token response shape (values redacted): \`${JSON.stringify(manifest.tokenShape)}\``, '');

  L.push('## Endpoints', '');
  L.push('| Endpoint | Requests | Status codes | Records | Non-null fields | Avg ms |', '|---|---|---|---|---|---|');
  for (const [name, { entries, stats }] of byEndpoint) {
    const codes = countBy(entries.map((e) => String(e.status)));
    const avg = Math.round(entries.reduce((s, e) => s + e.ms, 0) / Math.max(entries.length, 1));
    L.push(`| ${name} | ${entries.length} | ${fmtCounts(codes)} | ${stats.records} | ${stats.fields.size} | ${avg} |`);
  }
  const fileCodes = countBy(fileEntries.map((e) => String(e.status)));
  L.push(`| activity-file | ${fileEntries.length} | ${fmtCounts(fileCodes)} | ${fits.length} FIT${otherFiles.length ? ` + ${otherFiles.length} other` : ''} | — | — |`);
  const errors = manifest.entries.filter((e) => e.error);
  if (errors.length) {
    L.push('', '**Errors:**', '');
    for (const e of errors.slice(0, 30)) L.push(`- \`${e.endpoint}\` ${e.status}: ${oneLine(e.error!)}`);
  }

  L.push('', '## M0 questions — evidence', '');
  L.push('Field paths matching each question, with how many records had a non-null value. Read and judge; this is a search, not an answer.', '');
  for (const { q, endpoints, pattern } of QUESTIONS) {
    L.push(`### ${q}`);
    let any = false;
    for (const ep of endpoints) {
      const s = byEndpoint.get(ep)?.stats;
      if (!s) continue;
      const hits = [...s.fields].filter(([p]) => pattern.test(p)).sort((a, b) => a[0].localeCompare(b[0]));
      if (!hits.length) continue;
      any = true;
      L.push(`- **${ep}** (${s.records} records): ${hits.slice(0, 25).map(([p, n]) => `\`${p}\` ${n}`).join(', ')}${hits.length > 25 ? ` … +${hits.length - 25}` : ''}`);
    }
    if (!any) L.push('- _no matching fields found_');
    L.push('');
  }

  L.push('## FIT files by sport', '');
  if (!fits.length) {
    L.push('_No FIT files._', '');
  } else {
    L.push('| Sport / sub-sport | Files | Integrity OK | Records w/ HR | Median record interval | Power | Running dynamics | Swim lengths | VO2max msgs | HRV msgs |', '|---|---|---|---|---|---|---|---|---|---|');
    const groups = groupBy(fits, (f) => `${f.sport} / ${f.subSport}`);
    for (const [k, list] of groups) {
      const rec = list.reduce((s, f) => s + f.records, 0);
      const hr = list.reduce((s, f) => s + f.recordsWithHr, 0);
      const intervals = list.map((f) => f.medianRecordIntervalS).filter((x): x is number => x != null);
      const dyn = [...new Set(list.flatMap((f) => f.runningDynamics))];
      L.push(
        `| ${k} | ${list.length} | ${list.filter((f) => f.integrity).length} | ${rec ? Math.round((hr / rec) * 100) : 0}% of ${rec} | ${intervals.length ? `${median(intervals)} s` : '—'} | ${list.filter((f) => f.hasPower).length}/${list.length} | ${dyn.join(', ') || '—'} | ${list.reduce((s, f) => s + f.swim.lengths, 0)} | ${list.reduce((s, f) => s + f.vo2Max.length, 0)} | ${list.reduce((s, f) => s + f.hrvMessages, 0)} |`,
      );
    }
    L.push('');
    for (const [k, list] of groups) {
      L.push(`<details><summary><b>${k}</b> — per-file detail and message fields</summary>`, '');
      for (const f of list) {
        L.push(
          `- \`${f.file}\`: ${f.records} records; TE ${JSON.stringify(f.trainingEffect)}; swim ${JSON.stringify(f.swim)}; vo2Max ${JSON.stringify(f.vo2Max)}${f.errors.length ? `; errors: ${f.errors.map(oneLine).join(' | ')}` : ''}`,
        );
      }
      L.push('');
      const types = new Map<string, Set<string>>();
      for (const f of list) for (const [t, fields] of Object.entries(f.messageFields)) {
        const set = types.get(t) ?? new Set();
        fields.forEach((x) => set.add(x));
        types.set(t, set);
      }
      for (const [t, fields] of [...types].sort()) L.push(`- **${t}**: ${[...fields].sort().join(', ')}`);
      L.push('', '</details>', '');
    }
  }

  L.push('## All fields per endpoint', '');
  for (const [name, { stats }] of byEndpoint) {
    L.push(`<details><summary><b>${name}</b> — ${stats.records} records, ${stats.fields.size} fields</summary>`, '');
    L.push('| Field | Non-null | Types |', '|---|---|---|');
    for (const [p, n] of [...stats.fields].sort((a, b) => a[0].localeCompare(b[0]))) {
      L.push(`| \`${p}\` | ${n}/${stats.records} | ${[...(stats.types.get(p) ?? [])].join(', ')} |`);
    }
    L.push('', '</details>', '');
  }

  writeFileSync(join(out, 'COVERAGE.md'), L.join('\n'));
}

function countBy(xs: string[]): Map<string, number> {
  const m = new Map<string, number>();
  for (const x of xs) m.set(x, (m.get(x) ?? 0) + 1);
  return m;
}
function fmtCounts(m: Map<string, number>): string {
  return [...m].map(([k, v]) => `${k}×${v}`).join(' ') || '—';
}
function groupBy<T>(xs: T[], key: (x: T) => string): Map<string, T[]> {
  const m = new Map<string, T[]>();
  for (const x of xs) m.set(key(x), [...(m.get(key(x)) ?? []), x]);
  return m;
}
function median(xs: number[]): number {
  const s = [...xs].sort((a, b) => a - b);
  return s[Math.floor(s.length / 2)]!;
}
function oneLine(s: string): string {
  return s.replace(/\s+/g, ' ').replace(/\|/g, '/').slice(0, 160);
}
